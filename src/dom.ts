// Tiny DOM helpers. Text is always set with textContent; only the static icon strings
// below and sanitised Markdown are ever assigned as HTML.

type Child = Node | string | null | undefined | false;
type Props = Record<string, unknown> & {
  class?: string;
  text?: string;
  on?: Record<string, (event: Event) => void>;
};

export function h<K extends keyof HTMLElementTagNameMap>(
  tag: K,
  props: Props = {},
  children: Child[] = [],
): HTMLElementTagNameMap[K] {
  const el = document.createElement(tag);
  for (const [key, value] of Object.entries(props)) {
    if (value === undefined || value === null || value === false) continue;
    if (key === "class") el.className = String(value);
    else if (key === "text") el.textContent = String(value);
    else if (key === "on") {
      for (const [type, handler] of Object.entries(value as Record<string, EventListener>)) {
        el.addEventListener(type, handler);
      }
    } else if (key in el && typeof value !== "string") {
      (el as unknown as Record<string, unknown>)[key] = value;
    } else {
      el.setAttribute(key, value === true ? "" : String(value));
    }
  }
  for (const child of children) {
    if (child === null || child === undefined || child === false) continue;
    el.append(child);
  }
  return el;
}

